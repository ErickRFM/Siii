import {test,expect} from '@playwright/test';
import AxeBuilder from '@axe-core/playwright';
import pg from 'pg';
import argon2 from 'argon2';
import {randomUUID} from 'node:crypto';
import {generate} from 'otplib';
import {NodeCryptoPlugin} from '@otplib/plugin-crypto-node';
import {isolatedDatabaseUrl} from '../support/database-url';
const sql=new pg.Client({connectionString:isolatedDatabaseUrl()}),password='Synthetic-mfa-guidance-2026!';
let username:string;
test.beforeAll(async()=>{
 await sql.connect();username='mfa-help-'+randomUUID().slice(0,8);
 const person=(await sql.query("INSERT INTO people(first_name,last_name) VALUES('QA','Ayuda MFA') RETURNING id")).rows[0].id;
 const hash=await argon2.hash(password,{type:argon2.argon2id,memoryCost:65536,timeCost:3,parallelism:1});
 await sql.query('INSERT INTO platform_users(person_id,username,password_hash) VALUES($1,$2,$3)',[person,username,hash]);
});
test.afterAll(async()=>{await sql.end()});
test('manual key fragments stay local, restart requires a password and six app digits activate MFA',async({page})=>{
 let verificationRequests=0;page.on('request',request=>{if(request.url().endsWith('/api/v1/auth/mfa/verify')&&request.method()==='POST')verificationRequests++});
 await page.goto('/login');await page.getByLabel('Usuario institucional').fill(username);await page.getByLabel('Contraseña',{exact:true}).fill(password);await page.getByRole('button',{name:'Entrar al sistema'}).click();await expect(page).toHaveURL(/\/dashboard$/);
 await page.goto('/dashboard/security');await page.getByLabel('Contraseña actual para activar').fill(password);
 const pending=page.waitForResponse(response=>response.url().endsWith('/api/v1/auth/mfa/enroll')&&response.request().method()==='POST');
 await page.getByRole('button',{name:'Configurar autenticador',exact:true}).click();const first=await pending;expect(first.status()).toBe(201);
 const enrollmentId=(await first.json()).data.enrollmentId as string;
 const secret=await page.getByLabel('Clave manual del autenticador').inputValue();
 const code=page.getByLabel('Código para activar el autenticador');
 await expect(code).toHaveAttribute('aria-describedby',/mfa-enrollment-code-help/);
 await expect(page.getByText(/TOTP.*SHA-1.*6.*30/)).toBeVisible();
 const firstLetter=secret.search(/[A-Z]/),start=Math.min(Math.max(firstLetter,0),secret.length-6),fragment=firstLetter<0?'ABCDEF':secret.slice(start,start+6);
 await code.pressSequentially(fragment);
 await expect(page.locator('#mfa-enrollment-format-error')).toContainText('6 números');await expect(code).toBeFocused();
 await page.getByRole('button',{name:'Activar autenticador',exact:true}).click();expect(verificationRequests).toBe(0);
 await code.fill('123');await page.getByRole('button',{name:'Activar autenticador',exact:true}).click();
 await expect(page.locator('#mfa-enrollment-format-error')).toContainText('6 números');expect(verificationRequests).toBe(0);
 expect((await sql.query('SELECT attempts FROM auth_mfa_enrollments WHERE id=$1',[enrollmentId])).rows[0].attempts).toBe(0);
 await page.getByRole('button',{name:'Reiniciar activación',exact:true}).click();await expect(page.getByLabel('Clave manual del autenticador')).toHaveCount(0);await expect(page.getByLabel('Contraseña actual para activar')).toBeFocused();
 await page.getByLabel('Contraseña actual para activar').fill(password);
 await page.getByRole('button',{name:'Iniciar nueva activación',exact:true}).click();
 const replacement=await page.getByLabel('Clave manual del autenticador').inputValue();expect(replacement).not.toBe(secret);
 expect((await sql.query('SELECT consumed_at IS NOT NULL AS consumed FROM auth_mfa_enrollments WHERE id=$1',[enrollmentId])).rows[0].consumed).toBe(true);
 await code.fill(await generate({secret:replacement,algorithm:'sha1',digits:6,period:30,crypto:new NodeCryptoPlugin()}));
 const verified=page.waitForResponse(response=>response.url().endsWith('/api/v1/auth/mfa/verify')&&response.request().method()==='POST');
 await page.getByRole('button',{name:'Activar autenticador',exact:true}).click();expect((await verified).status()).toBe(200);expect(verificationRequests).toBe(1);
 await expect(page.getByRole('region',{name:'Guarda estos códigos de recuperación'}).locator('code')).toHaveCount(10);await expect(page.getByLabel('Clave manual del autenticador')).toHaveCount(0);
 const axe=await new AxeBuilder({page}).withTags(['wcag2a','wcag2aa','wcag21aa','wcag22aa']).analyze();expect(axe.violations).toEqual([]);
});
